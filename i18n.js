// Language switcher core
// =================================================================
(function() {
  const DEFAULT = 'pt';
  const SUPPORTED = ['pt', 'en', 'es', 'fr', 'zh'];

  function detect() {
    const stored = localStorage.getItem('fishify-lang');
    if (stored && SUPPORTED.includes(stored)) return stored;
    const browser = (navigator.language || 'pt').slice(0, 2).toLowerCase();
    return SUPPORTED.includes(browser) ? browser : DEFAULT;
  }

  window.t = function(key) {
    const lang = window.FISHIFY_LANG || DEFAULT;
    return (window.FISHIFY_I18N[lang] && window.FISHIFY_I18N[lang][key])
        || window.FISHIFY_I18N[DEFAULT][key]
        || key;
  };

  window.applyLang = function(lang) {
    if (!SUPPORTED.includes(lang)) lang = DEFAULT;
    window.FISHIFY_LANG = lang;
    localStorage.setItem('fishify-lang', lang);
    document.documentElement.setAttribute('lang', lang);

    // Replace all elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = t(key);
      if (val) el.innerHTML = val;
    });
    // Replace attributes via data-i18n-attr (e.g. "placeholder:menu.search.placeholder|aria-label:menu.search.aria")
    document.querySelectorAll('[data-i18n-attr]').forEach(el => {
      const spec = el.getAttribute('data-i18n-attr');
      spec.split('|').forEach(pair => {
        const [attr, key] = pair.split(':');
        if (attr && key) el.setAttribute(attr, t(key));
      });
    });

    // Update active flag
    document.querySelectorAll('.flag-btn').forEach(btn => {
      btn.classList.toggle('active', btn.dataset.lang === lang);
      btn.setAttribute('aria-pressed', btn.dataset.lang === lang ? 'true' : 'false');
    });

    // Trigger re-render for dynamic content (menu page)
    if (typeof window.onLangChange === 'function') window.onLangChange(lang);
  };

  window.initLangSwitcher = function() {
    const containers = document.querySelectorAll('.lang-switcher');
    containers.forEach(container => {
      container.innerHTML = SUPPORTED.map(lang =>
        `<button class="flag-btn" data-lang="${lang}" aria-label="${lang.toUpperCase()}" aria-pressed="false" title="${lang.toUpperCase()}">${window.FISHIFY_FLAGS[lang]}</button>`
      ).join('');
    });
    document.querySelectorAll('.flag-btn').forEach(btn => {
      btn.addEventListener('click', () => window.applyLang(btn.dataset.lang));
    });
    window.applyLang(detect());
  };
})();
